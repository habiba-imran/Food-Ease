import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:1440,height:1000}});
const initialImages=[];page.on('request',r=>{if(r.url().includes('/static/img/'))initialImages.push(r.url())});
await page.goto('http://127.0.0.1:8193/?design=delivery-7',{waitUntil:'networkidle'});
await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
const initial={hiddenPreviewFetched:initialImages.some(u=>u.includes('960.webp')||u.includes('optimized/')),hero:await page.locator('.hero-product').evaluate(i=>({src:i.currentSrc,complete:i.complete,width:i.naturalWidth})),navbarTop:await page.locator('.site-header').evaluate(e=>e.getBoundingClientRect().top)};
await page.screenshot({path:'../artifacts/performance/desktop-hero.png'});
await page.locator('.spotlight-intro h2').scrollIntoViewIfNeeded();
await page.waitForTimeout(900);
await page.screenshot({path:'../artifacts/performance/desktop-scroll.png'});
const scrolling={navbarTop:await page.locator('.site-header').evaluate(e=>e.getBoundingClientRect().top),textOpacity:await page.locator('.spotlight-intro h2').evaluate(e=>getComputedStyle(e).opacity)};
await page.setViewportSize({width:375,height:812});
await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
await page.screenshot({path:'../artifacts/performance/mobile-top.png'});
const mobile={navbarTop:await page.locator('.site-header').evaluate(e=>e.getBoundingClientRect().top),overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)};
const report={initial,scrolling,mobile};console.log(JSON.stringify(report));
await writeFile('../artifacts/performance/interaction-audit.json',JSON.stringify(report,null,2));
await browser.close();
if(initial.hiddenPreviewFetched||!initial.hero.complete||initial.navbarTop!==0||scrolling.navbarTop!==0||scrolling.textOpacity!=='1'||mobile.navbarTop!==0||mobile.overflow)process.exitCode=1;
